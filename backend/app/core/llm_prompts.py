def build_system_prompt(*, after_count: int) -> str:
    """
    상황(after 이미지 유무) 에 따라 **하나의 예시만** 주입한 시스템 프롬프트를 반환한다.

    - after_count > 0  → MODE A 예시만 주입.
    - after_count == 0 → MODE B 예시만 주입.

    2B 급 작은 모델이 두 예시 중 NC 와 어휘가 겹치는 쪽을 그대로 베끼는 경향을
    차단하기 위해, 현재 생성 시점에 해당하지 않는 예시는 숨긴다.
    """
    example_block = _EXAMPLE_MODE_A if after_count > 0 else _EXAMPLE_MODE_B
    return _SYSTEM_PROMPT_TEMPLATE.format(example_block=example_block)


# 하위 호환 — 기존 import 경로 유지. 테스트와 호출부가 이 상수를 직접 참조한다.
# 이 상수는 '두 예시가 모두 보이는' 버전을 가진다 — 프롬프트 구조/문구의 회귀 테스트용.
# 실제 inference 에서는 llm_scheduler 가 build_system_prompt(after_count=...) 를 호출해
# 해당 상황에 맞는 예시 하나만 주입한다.
SYSTEM_PROMPT_CORRECTIVE_ACTION = _SYSTEM_PROMPT_TEMPLATE.format(
    example_block=_EXAMPLE_MODE_A + "\n" + _EXAMPLE_MODE_B
)


def build_user_prompt(
    *,
    nc_title: str,
    nc_description: str,
    nc_requirement: Optional[str],
    nc_type: Optional[str],
    severity: Optional[str],
    control_code: Optional[str],
    control_name: Optional[str],
    before_count: int = 0,
    after_count: int = 0,
    support_count: int = 0,
    reference_count: int = 0,
    skipped_non_image_count: int = 0,
    ai_hint: Optional[str] = None,
) -> str:
    """
    부적합과 첨부 증적 요약을 바탕으로 LLM user 메시지 본문을 조립한다.

    이미지(base64)는 별도 필드로 Ollama 에 전달되며, 본문에는 역할별 개수와 순서만
    기재한다. 호출부(llm_scheduler)는 이미지 바이트를 before → after → support → reference
    순으로 전달해야 본 프롬프트의 '먼저 설명되는 N장 = 조치 전' 기술이 실제와 일치한다.
    """
    control_line = ""
    if control_code or control_name:
        control_line = (
            f"통제항목: {control_code or ''} {control_name or ''}".strip()
        )

    meta_lines = [line for line in [
        control_line,
        f"결함 유형: {nc_type}" if nc_type else None,
        f"심각도: {severity}" if severity else None,
    ] if line]

    meta_block = "\n".join(meta_lines)
    if meta_block:
        meta_block = "[결함 분류]\n" + meta_block + "\n\n"

    requirement_block = ""
    if nc_requirement:
        requirement_block = f"[요구사항]\n{nc_requirement.strip()}\n\n"

    # [심사원 추가 지시] — NC.ai_hint 에 값이 있을 때만 노출.
    # 도메인 용어(예: '이전 비밀번호 기억 = password history / 동일 비밀번호 재사용 차단')
    # 교정 등 심사원이 직접 지정한 지시를 모델이 놓치지 않도록 [요구사항] 직후에 배치한다.
    # 문구는 '반드시 따르라' 가 아닌 '우선 반영' 으로 해, 잘못 쓴 힌트가 4-섹션 구조를
    # 깨지 않도록 방어한다.
    hint_block = ""
    if ai_hint and ai_hint.strip():
        hint_block = (
            "[심사원 추가 지시] (용어 교정·제약 — 일반 규칙보다 우선 반영)\n"
            f"{ai_hint.strip()}\n\n"
        )

    # 이미지 순서 = before → after → support → reference.
    # 본문에서 각 구간의 "첫 N장" 을 명시해 모델이 역할을 혼동하지 않게 한다.
    lines: list[str] = ["[첨부 증적]"]
    cursor = 1
    if before_count > 0:
        end = cursor + before_count - 1
        range_str = f"{cursor}번" if cursor == end else f"{cursor}~{end}번"
        lines.append(f"- {range_str} 이미지: 조치 전 (현재 문제 상태) — {before_count}장")
        cursor = end + 1
    if after_count > 0:
        end = cursor + after_count - 1
        range_str = f"{cursor}번" if cursor == end else f"{cursor}~{end}번"
        lines.append(f"- {range_str} 이미지: 조치 후 (개선 완료 상태) — {after_count}장")
        cursor = end + 1
    if support_count > 0:
        end = cursor + support_count - 1
        range_str = f"{cursor}번" if cursor == end else f"{cursor}~{end}번"
        lines.append(
            f"- {range_str} 이미지: 보조 증적 (신청서/결재/정책 등) — {support_count}장"
        )
        cursor = end + 1
    if reference_count > 0:
        end = cursor + reference_count - 1
        range_str = f"{cursor}번" if cursor == end else f"{cursor}~{end}번"
        lines.append(
            f"- {range_str} 이미지: 참고 (역할 미지정) — {reference_count}장"
        )
    if len(lines) == 1:
        lines.append("- 첨부된 이미지 증적이 없습니다.")
    if skipped_non_image_count > 0:
        lines.append(
            f"- 비이미지 증적 {skipped_non_image_count}건은 본 모델에 전달되지 않았습니다."
        )
    attachment_block = "\n".join(lines)

    # 역할 혼동 방지 힌트. 시스템 프롬프트에도 같은 규칙이 있지만 user 메시지 꼬리에
    # 다시 두면 모델이 생성 시점에 잊지 않는다.
    # - before+after 공존: 각각의 섹션에서만 사용하도록 분리.
    # - after-only: **#1 에 after 이미지 내용을 절대 끌어오지 않도록** 강하게 차단.
    #   관찰된 버그 사례 — 성공 로그가 담긴 after 스크린샷의 타임스탬프/IP 를
    #   "남지 않음" 이라는 부정 서술과 함께 #1 에 인용하는 모순 출력을 막기 위함.
    role_hint = ""
    if before_count > 0 and after_count > 0:
        role_hint = (
            "\n(#1 은 조치 전 이미지만, #3 은 조치 후 이미지만 근거로 사용하세요.)"
        )
    elif after_count > 0 and before_count == 0:
        role_hint = (
            "\n\n※ 첨부 이미지는 **모두 조치 후** 상태입니다."
            " 조치 후 이미지의 **화면 값·타임스탬프·IP·계정·성공 메시지** 를 #1 결함"
            " 현상에 인용하지 마세요. #1 결함 현상은 오직 [결함 내용] 텍스트만 근거로"
            " 서술하세요 (이미지는 #3 개선 조치 내역의 근거로만 사용)."
            "\n특히 아래 패턴 금지 — after 이미지에서 IP/시간/ID 를 뽑아 #1 세부 항목"
            " 불릿(`- Client IP: …`, `- Date/Time: …`)으로 나열하는 것은 절대 금지."
            " after 이미지는 '기록이 남고 있다' 는 증거이므로 이를 '남지 않는다' 는"
            " 결함 서술의 근거로 쓰는 것은 자기모순입니다."
        )

    # 조치 후 이미지가 없을 때의 강제 모드 힌트 (MODE B).
    # 시스템 프롬프트에도 같은 규칙이 있지만, 관찰된 hallucination 패턴상
    # user 메시지 '끝'에 재차 명시해야 모델이 이 시점에 잊지 않는다.
    no_after_hint = ""
    if after_count == 0:
        no_after_hint = (
            "\n\n※ 조치 후 이미지가 **없습니다**. #3 개선 조치 내역은 MODE B 규칙을"
            " 반드시 적용하세요:"
            "\n  - 각 ` o ` 불릿을 '조치 예정: ' 으로 시작할 것."
            "\n  - 다음 단어·어미는 절대 사용 금지: '확인함', '확인됩니다',"
            " '적용하였으며', '변경되었습니다', '수정하였습니다', '완료하였습니다',"
            " '반영되었습니다', '조치하였습니다'."
            "\n  - 가상의 화면 문구를 큰따옴표로 인용하지 말 것."
            "\n  - 필요한 개발·운영 조치를 '~할 예정', '~하도록 계획' 형태로만 기술."
            "\n  - #1 의 `o` 불릿 개수와 **정확히 같은 수** 의 `o` 불릿만 쓰세요."
            " 같은 조치를 바꿔 쓴 중복 불릿 금지. #1 문장을 다시 풀어쓰지 마세요."
        )

    # 조치 후 이미지가 있을 때의 MODE A 강제 힌트. after 만 있고 before 가 없는 케이스에서
    # 모델이 혼란스러워 MODE B ("조치 예정") 로 흘러가는 관찰 사례를 막기 위함.
    after_mode_hint = ""
    if after_count > 0:
        after_mode_hint = (
            "\n\n※ **조치 후 이미지가 이미 있으므로 조치는 완료된 상태** 입니다."
            " #3 개선 조치 내역은 반드시 MODE A (조치 완료 기술) 로 작성하세요."
            "\n  - **금지 접두사**: '조치 예정:' 으로 시작하는 불릿 절대 금지."
            "\n  - **금지 어미**: '~할 예정', '~하도록 계획', '~검토 후 적용' 등 미래형 금지."
            "\n  - **필수 어미**: '완료함', '적용함', '추가함', '반영함', '수정함' 등"
            " 완결형 과거·현재형만 사용."
            "\n  - [결함 내용] 이 '~남지 않음', '~미적용' 과 같은 부정형이어도 #3 는"
            " '~를 추가 적용하여 남도록 완료함', '~를 적용함' 과 같이 **이미 해결된**"
            " 형태로 서술."
            "\n  - 조치 후 이미지에 실제 보이는 문구·값은 #3 의 세부 항목(`- ...`) 에서만"
            " 인용하세요. #1 결함 현상에는 절대 가져오지 마세요."
        )

    # 다수 이슈 분리 힌트 — [결함 내용] 에 번호 매기기(1)/2)), 글머리표(-, •),
    # 줄바꿈 기반 열거가 있을 때 모델이 하나로 뭉뚱그려 쓰지 않고 **항목별 distinct 불릿**
    # 으로 분리하도록 강제. 관찰된 실패 — NC #7 처럼 "1) PW 발급 관리, 2) Staff Action"
    # 두 메뉴가 있는데 모델이 한쪽(Staff Action) 내용만 중복 복사하는 버그.
    enumeration_hint = ""
    desc = nc_description or ""
    # 간단 heuristic — `1)`, `2)` 또는 `1.`, `2.` 또는 `- ` 가 두 번 이상 보이면 적용.
    numbered_count = len(re.findall(r"(?:^|\n)\s*(?:\d[\)\.]|[-•])\s+", desc))
    if numbered_count >= 2:
        enumeration_hint = (
            "\n\n※ [결함 내용] 에 **여러 개의 번호/글머리 항목** 이 있으면 각 항목을"
            " **서로 다른** ` o ` 불릿으로 분리해 기술하세요."
            "\n  - 각 불릿의 **주어/대상** (메뉴명·자산명·대상 화면) 이 서로 달라야 합니다."
            "\n  - 같은 문장을 두 번 복사하는 중복 금지."
            "\n  - 예: [결함 내용] 이 '1) 방화벽 … 포트 개방 / 2) EPP Agent … 미설치'"
            " 이면 #1 은 `o 방화벽 …`, `o EPP Agent …` 2개의 서로 다른 주어를 가진"
            " 불릿이어야 합니다."
            "\n  - #3 조치 내역도 **각 항목에 1:1 대응** 하는 서로 다른 조치를 써야 합니다."
        )

    # 관찰된 실패 패턴: 모델이 [결함 내용] 의 부정 표현('남지 않음', '미적용')을
    # 반대 극성('남는 상태', '적용됨')으로 뒤집는 경우가 있다. user 메시지 '끝'에서
    # 한 번 더 경고하여 잊어버리지 않게 한다. 시스템 프롬프트에도 같은 규칙이
    # 있지만 user tail 재강조가 효과적이라는 관찰에 기반.
    polarity_hint = (
        "\n\n※ [결함 내용] 의 부정 표현(예: '남지 않음', '미적용', '미흡')은 #1 에서도"
        " 동일한 극성으로 그대로 유지하세요. 절대 '남는 상태', '적용됨' 등 반대 뜻으로"
        " 바꾸지 마세요. 또한 #1 에 '통제항목 X 에 따라…' 같은 요구사항 서술은 금지 —"
        " 이는 #2 에서만 다룹니다."
    )

    # 값 보존 힌트 — [결함 내용] 에 구체적 값이 있으면 그대로 복사해서 쓰라고 강조.
    # 참조 PDF 스타일의 '풍부함' 은 대부분 원문에 이미 있는 값을 보존하는 데서 온다.
    value_hint = (
        "\n\n※ [결함 내용]/[요구사항] 에 포함된 **구체적 값**(IP/CIDR, 포트 번호,"
        " 정책 번호, 계정·호스트명, 파일·서비스명, 수치 등)은 #1 과 #3 불릿에"
        " **원문 그대로** 복사해서 포함시키세요. 일반화하거나 생략하지 마세요."
        " 조치 내역은 가능하면 'X → Y' 형식의 Before/After 대비를 불릿에 넣으세요."
    )

    # 출력 형식 힌트 — 계층 불릿 구조를 쓰라고 user tail 에서 한 번 더 환기.
    bullet_hint = (
        "\n\n※ 각 섹션은 반드시 ` o ` (공백+o+공백) 으로 시작하는 불릿으로 기술하세요."
        " 세부 항목은 `   - ` (들여쓰기 3칸+하이픈+공백) 을 사용합니다. 평문 단락으로"
        " 쓰지 마세요."
    )

    return (
        f"{meta_block}"
        f"[결함 제목]\n{nc_title.strip()}\n\n"
        f"[결함 내용] (#1 결함 현상의 주요 근거)\n{nc_description.strip()}\n\n"
        f"{requirement_block}"
        f"{hint_block}"
        f"{attachment_block}"
        f"{role_hint}"
        f"{no_after_hint}"
        f"{after_mode_hint}"
        f"{enumeration_hint}"
        f"{polarity_hint}"
        f"{value_hint}"
        f"{bullet_hint}\n\n"
        f"위 정보를 바탕으로 보완조치내역서 초안을 작성해주세요."
    )


